#!/usr/bin/env node
'use strict';
/**
 * Build script: assembles dist/speiihos.cjs from the source in bin/speiihos.cjs.
 *
 * Why a build step?
 *   - Keeps bin/ as the editable source (no node_modules clutter in dist/).
 *   - Lets us stamp the version, strip dev comments, and validate the output
 *     before npm publish / npm pack picks it up from dist/.
 *   - Mirrors how the Python side uses `python -m build` → dist/*.whl.
 *
 * Usage:
 *   node scripts/build.cjs          # writes dist/speiihos.cjs
 *   npm run build                   # same via package.json
 *   npm run prepublishOnly          # called automatically by npm publish
 */

const fs   = require('node:fs');
const path = require('node:path');

const ROOT    = path.resolve(__dirname, '..');
const SRC     = path.join(ROOT, 'bin', 'speiihos.cjs');
const DIST    = path.join(ROOT, 'dist');
const OUT     = path.join(DIST, 'speiihos.cjs');
const PKG     = require(path.join(ROOT, 'package.json'));

// ── 1. Read source ────────────────────────────────────────────────────────────
if (!fs.existsSync(SRC)) {
  console.error(`[build] ERROR: source file not found: ${SRC}`);
  process.exit(1);
}
let source = fs.readFileSync(SRC, 'utf8');

// ── 2. Stamp the version comment right after the shebang line ────────────────
const banner = `// speiihosting v${PKG.version} — auto-generated by scripts/build.cjs, do not edit dist/ directly.\n`;
const lines = source.split('\n');
const shebangLine = lines[0].startsWith('#!') ? lines.shift() : null;
// Strip any existing banner line so re-runs are idempotent
if (lines[0].startsWith('// speiihosting v')) lines.shift();
// Re-assemble: shebang (if any) → banner → rest of source
source = (shebangLine ? shebangLine + '\n' : '') + banner + lines.join('\n');

// ── 3. Write dist/ ────────────────────────────────────────────────────────────
fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(OUT, source, 'utf8');
fs.chmodSync(OUT, 0o755);

console.log(`[build] dist/speiihos.cjs  (${(source.length / 1024).toFixed(1)} KB)  v${PKG.version}`);
